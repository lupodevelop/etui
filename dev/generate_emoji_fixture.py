#!/usr/bin/env python3
"""Regenerate the offline emoji-width oracle from pinned Unicode 16 data."""

import hashlib
from pathlib import Path
import subprocess
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
DATA = {
    "emoji/emoji-variation-sequences.txt":
        "71d93ec015011371a027ba2bc0a63155d381c6e0b94a586c1a88a49400cd6864",
    "EastAsianWidth.txt":
        "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b",
}


def download(name):
    with urlopen("https://www.unicode.org/Public/16.0.0/ucd/" + name, timeout=30) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != DATA[name]:
        raise ValueError("Unicode source checksum changed: " + name)
    return data.decode("utf-8")


def records(data):
    for line in data.splitlines():
        fields = line.split("#", 1)[0].strip()
        if fields:
            yield [field.strip() for field in fields.split(";")]


def main():
    bases = sorted({
        int(fields[0].split()[0], 16)
        for fields in records(download("emoji/emoji-variation-sequences.txt"))
    })
    wide = []
    for codepoints, width in records(download("EastAsianWidth.txt")):
        if width in {"W", "F"}:
            bounds = codepoints.split("..")
            wide.append((int(bounds[0], 16), int(bounds[-1], 16)))

    # Expected values never call or parse production code. VS16 is always 2.
    # VS15 narrows BMP emoji; supplementary bases retain the existing policy:
    # pictograph blocks at/above U+1F300 are wide, lower bases follow EAW.
    rows = []
    for base in bases:
        text_width = 1 if base < 0x1F000 else 2 if (
            base >= 0x1F300 or any(lo <= base <= hi for lo, hi in wide)
        ) else 1
        rows.append(f'    #("\\u{{{base:X}}}", {text_width}),')
    fixture = ROOT / "test/emoji_width_fixture.gleam"
    fixture.write_text(
        "// Generated by dev/generate_emoji_fixture.py; do not edit.\n"
        "// Unicode 16.0 emoji-variation-sequences.txt and EastAsianWidth.txt.\n"
        "// Sources: https://www.unicode.org/Public/16.0.0/ucd/\n"
        "// Data license: https://www.unicode.org/license.txt\n"
        "// Each pair is a supported base and its expected VS15 cell width.\n"
        "pub fn bases() -> List(#(String, Int)) {\n  [\n"
        + "\n".join(rows) + "\n  ]\n}\n"
    )
    subprocess.run(["gleam", "format", str(fixture)], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
